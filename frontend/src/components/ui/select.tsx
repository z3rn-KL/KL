function Select({
  items,
  children,
  ...props
}: SelectPrimitive.Root.Props<any, any>) {
  // Automatically extract { [value]: label } from children if items prop is not explicitly passed
  const resolvedItems = React.useMemo(() => {
    if (items) return items;
    const map: Record<string, React.ReactNode> = {};
    function traverse(node: React.ReactNode) {
      if (!node) return;
      if (Array.isArray(node)) {
        node.forEach(traverse);
        return;
      }
      if (React.isValidElement(node)) {
        const p = node.props as Record<string, any>;
        if (p) {
          if (p.value !== undefined && p.children !== undefined) {
            // If children is ItemText or raw string/node
            map[String(p.value)] = p.children;
          }
          if (p.children) {
            traverse(p.children);
          }
        }
      }
    }
    traverse(children);
    return Object.keys(map).length > 0 ? map : undefined;
  }, [items, children]);

  return (
    <SelectPrimitive.Root items={items ?? resolvedItems} {...props}>
      {children}
    </SelectPrimitive.Root>
  );
}

